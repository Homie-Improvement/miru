RSpec.describe "Committed-data test mode lock-wait observation", committed_data: true do
  # "Synchronize contender startup and observe the database blocker, with a bounded wait, before releasing the transaction."
  # A contender that never reported its pid (its pop timed out and gave nil) must not pass as blocked,
  # even when some other backend really is waiting on the same holder.
  it "does not count a lock wait for a contender whose pid never arrived, even while another backend waits on the holder" do
    holder_pid = Queue.new
    waiter_pid = Queue.new
    locked = Queue.new
    release = Queue.new

    holder = committed_data_thread(holder_pid) do
      TimekeepingOwnership.transaction do
        TimekeepingOwnership.lock("FOR UPDATE").find(TimekeepingOwnership::SINGLETON_ID)
        locked << true
        release.pop(timeout: 10)
      end
    end
    expect(locked.pop(timeout: 5)).to be(true)
    holding = holder_pid.pop(timeout: 5)

    waiter = committed_data_thread(waiter_pid) do
      TimekeepingOwnership.where(id: TimekeepingOwnership::SINGLETON_ID).update_all(handoff_step: "close_admission")
    end
    waiting = waiter_pid.pop(timeout: 5)

    begin
      real_wait_seen = blocked_by?(waiting, holding)
      missing_contender_seen = blocked_by?(nil, holding, within: 0.3)
    ensure
      release << true
    end
    [holder, waiter].each { |thread| thread.join(5) }

    expect(real_wait_seen).to be(true)
    expect(missing_contender_seen).to be(false)
  end
end
