RSpec.describe "Committed-data test mode", committed_data: true do
  # "Synchronize contender startup and observe the database blocker, with a bounded wait, before releasing the transaction."
  # A real wait exists here (waiter behind holder), plus an idle bystander connection. Naming the bystander as
  # the holder, or the bystander as the waiter, must not count as observing the blocker.
  it "counts a lock wait only when the named holder is the one blocking the named waiter" do
    holder_pids = Queue.new
    waiter_pids = Queue.new
    bystander_pids = Queue.new
    locked = Queue.new
    release = Queue.new
    bystander_go = Queue.new

    holder = committed_data_thread(holder_pids) do
      ActiveRecord::Base.transaction do
        TimekeepingOwnership.lock("FOR UPDATE").find(TimekeepingOwnership::SINGLETON_ID)
        locked << true
        release.pop(timeout: 10)
      end
    end
    expect(locked.pop(timeout: 5)).to be(true)

    waiter = committed_data_thread(waiter_pids) do
      TimekeepingOwnership.where(id: TimekeepingOwnership::SINGLETON_ID).update_all(handoff_step: "close_admission")
    end
    bystander = committed_data_thread(bystander_pids) { bystander_go.pop(timeout: 10) }

    holder_pid = holder_pids.pop(timeout: 5)
    waiter_pid = waiter_pids.pop(timeout: 5)
    bystander_pid = bystander_pids.pop(timeout: 5)

    begin
      really_blocked = blocked_by?(waiter_pid, holder_pid, within: 3)
      blocked_by_bystander = blocked_by?(waiter_pid, bystander_pid, within: 0.3)
      bystander_blocked = blocked_by?(bystander_pid, holder_pid, within: 0.3)
    ensure
      release << true
    end

    expect(really_blocked).to be(true)
    expect(blocked_by_bystander).to be(false)
    expect(bystander_blocked).to be(false)
  ensure
    release&.push(true)
    bystander_go&.push(true)
    [holder, waiter, bystander].compact.each { |thread| thread.join(5) }
  end
end

