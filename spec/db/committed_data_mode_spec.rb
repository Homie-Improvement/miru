# frozen_string_literal: true

require "rails_helper"

# The examples run in the order written: the later ones check what the
# earlier ones left behind.
RSpec.describe "Committed-data test mode", committed_data: true, order: :defined do
  it "commits rows that a second database connection can read" do
    invoice = create(:invoice)

    seen_elsewhere = committed_data_thread { Invoice.where(id: invoice.id).exists? }.value

    expect(seen_elsewhere).to be(true)
  end

  it "starts the next example with no committed invoice left behind" do
    expect(Invoice.count).to eq(0)
  end

  it "lets an example set a handoff step on the ownership row" do
    TimekeepingOwnership.current.update!(handoff_step: "close_admission")

    seen_elsewhere = committed_data_thread { TimekeepingOwnership.current.handoff_step }.value

    expect(seen_elsewhere).to eq("close_admission")
  end

  it "restores the ownership row with no handoff step for the next example" do
    expect(TimekeepingOwnership.current).to have_attributes(handoff_step: nil, generation: 1, owner: "monolith")
  end
end

# Generated by Descant: acceptance tests below.
RSpec.describe "Committed-data lock-wait helpers", committed_data: true do
  # Starts a thread that holds FOR UPDATE on the ownership row until release
  # gets a value, and returns once the lock is taken.
  def hold_ownership_row_for_lock_wait_spec(holder_pids, release)
    locked = Queue.new
    holder = committed_data_thread(holder_pids) do
      TimekeepingOwnership.transaction do
        TimekeepingOwnership.lock("FOR UPDATE").find(TimekeepingOwnership::SINGLETON_ID)
        locked << true
        release.pop(timeout: 10)
      end
    end
    expect(locked.pop(timeout: 5)).to be(true)
    holder
  end

  def update_ownership_row_for_lock_wait_spec(waiter_pids, &before_update)
    committed_data_thread(waiter_pids) do
      before_update&.call
      TimekeepingOwnership.where(id: TimekeepingOwnership::SINGLETON_ID).update_all(handoff_step: "close_admission")
    end
  end

  # "There is no signal that this thread acquired a connection or attempted its UPDATE."
  # The block waits until the main thread has the pid, so a pid pushed only after the block ran would never
  # arrive in time; and a pid from any connection other than the block's would point the blocker check at
  # the wrong session.
  it "pushes the pid of the block's own connection, once, before the block runs" do
    pids = Queue.new
    pid_received = Queue.new

    thread = committed_data_thread(pids) do
      pid_received.pop(timeout: 5)
      ActiveRecord::Base.connection.select_value("SELECT pg_backend_pid()")
    end

    pushed_pid = pids.pop(timeout: 3)
    pid_received << true
    pid_inside_block = thread.join(5)&.value

    expect(pushed_pid).to be_a(Integer)
    expect(pushed_pid).to eq(pid_inside_block)
    expect(pushed_pid).not_to eq(ActiveRecord::Base.connection.select_value("SELECT pg_backend_pid()"))
    expect(pids).to be_empty
  ensure
    pid_received&.push(true)
    thread&.join(5)
  end

  it "reports a lock wait only for the waiting pid and the pid that holds the lock, in that order" do
    holder_pids = Queue.new
    waiter_pids = Queue.new
    release = Queue.new

    holder = hold_ownership_row_for_lock_wait_spec(holder_pids, release)
    waiter = update_ownership_row_for_lock_wait_spec(waiter_pids)

    begin
      holding_pid = holder_pids.pop(timeout: 5)
      waiting_pid = waiter_pids.pop(timeout: 5)
      really_blocked = blocked_by?(waiting_pid, holding_pid)
      reversed = blocked_by?(holding_pid, waiting_pid, within: 0.3)
      unrelated = blocked_by?(waiting_pid, ActiveRecord::Base.connection.select_value("SELECT pg_backend_pid()"), within: 0.3)
      # A contender whose pid pop timed out gives nil; it must not pass as
      # blocked while another backend really waits on the same holder.
      missing_contender = blocked_by?(nil, holding_pid, within: 0.3)
    ensure
      release << true
    end

    expect(really_blocked).to be(true)
    expect(reversed).to be(false)
    expect(unrelated).to be(false)
    expect(missing_contender).to be(false)
    expect(holder.join(5)).not_to be_nil
    expect(waiter.join(5)).not_to be_nil
    expect(TimekeepingOwnership.find(TimekeepingOwnership::SINGLETON_ID).handoff_step).to eq("close_admission")
  ensure
    release&.push(true)
    [holder, waiter].compact.each { |thread| thread.join(5) }
  end

  # "Synchronize contender startup and observe the database blocker, with a bounded wait, before releasing the transaction."
  # A real wait exists here (waiter behind holder), plus an idle bystander connection. Naming the bystander as
  # the holder, or the bystander as the waiter, must not count as observing the blocker.
  it "counts a lock wait only when the named holder is the one blocking the named waiter" do
    holder_pids = Queue.new
    waiter_pids = Queue.new
    release = Queue.new

    holder = hold_ownership_row_for_lock_wait_spec(holder_pids, release)
    waiter = update_ownership_row_for_lock_wait_spec(waiter_pids)
    # Opened outside the pool: the holder, the waiter and the main thread
    # already lease every connection the test pool has.
    bystander = ActiveRecord::Base.connection_pool.db_config.new_connection

    holder_pid = holder_pids.pop(timeout: 5)
    waiter_pid = waiter_pids.pop(timeout: 5)
    bystander_pid = bystander.select_value("SELECT pg_backend_pid()")
    expect([holder_pid, waiter_pid, bystander_pid]).to all(be_a(Integer))

    begin
      really_blocked = blocked_by?(waiter_pid, holder_pid, within: 3)
      blocked_by_bystander = blocked_by?(waiter_pid, bystander_pid, within: 0.3)
      bystander_blocked = blocked_by?(bystander_pid, holder_pid, within: 0.3)
    ensure
      release << true
    end

    expect(really_blocked).to be(true)
    expect(blocked_by_bystander).to be(false)
    expect(bystander_blocked).to be(false)
  ensure
    release&.push(true)
    [holder, waiter].compact.each { |thread| thread.join(5) }
    bystander&.disconnect!
  end

  # "These checks do not distinguish a database lock wait from a thread that has not reached its query."
  # The contender holds a connection but has not sent its statement, so the check must say it is not blocked
  # and stop polling at its bound; once the statement is sent, the same pid is seen waiting.
  it "does not report a contender that has not sent its query as blocked, and gives up at its deadline" do
    holder_pids = Queue.new
    contender_pids = Queue.new
    release = Queue.new
    go = Queue.new

    holder = hold_ownership_row_for_lock_wait_spec(holder_pids, release)
    contender = update_ownership_row_for_lock_wait_spec(contender_pids) { go.pop(timeout: 10) }
    contender_pid = contender_pids.pop(timeout: 5)
    holder_pid = holder_pids.pop(timeout: 5)

    begin
      started = Process.clock_gettime(Process::CLOCK_MONOTONIC)
      before_query = blocked_by?(contender_pid, holder_pid, within: 0.3)
      elapsed = Process.clock_gettime(Process::CLOCK_MONOTONIC) - started

      go << true
      after_query = blocked_by?(contender_pid, holder_pid)
    ensure
      go << true
      release << true
    end

    expect(before_query).to be(false)
    expect(elapsed).to be < 2
    expect(after_query).to be(true)
  ensure
    go&.push(true)
    release&.push(true)
    [holder, contender].compact.each { |thread| thread.join(5) }
  end
end
