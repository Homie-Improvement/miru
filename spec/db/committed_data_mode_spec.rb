RSpec.describe "Committed-data test mode", committed_data: true do
  # "There is no signal that this thread acquired a connection or attempted its UPDATE."
  # The block waits until the main thread has the pid, so a pid pushed only after the block ran would never
  # arrive in time; and a pid from any connection other than the block's would point the blocker check at
  # the wrong session.
  it "pushes the pid of the block's own connection before the block runs" do
    pids = Queue.new
    pid_received = Queue.new

    thread = committed_data_thread(pids) do
      pid_received.pop(timeout: 5)
      ActiveRecord::Base.connection.select_value("SELECT pg_backend_pid()")
    end

    pushed_pid = pids.pop(timeout: 3)
    pid_received << true
    pid_inside_block = thread.join(5)&.value

    expect(pushed_pid).not_to be_nil
    expect(pushed_pid).to eq(pid_inside_block)
    expect(pushed_pid).not_to eq(ActiveRecord::Base.connection.select_value("SELECT pg_backend_pid()"))
  ensure
    pid_received&.push(true)
    thread&.join(5)
  end
end

