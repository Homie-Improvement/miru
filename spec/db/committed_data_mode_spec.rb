RSpec.describe "Committed-data lock wait observed", committed_data: true do
  it "reports a connection waiting on another connection's row lock as blocked by it" do
    holder_pids = Queue.new
    contender_pids = Queue.new
    locked = Queue.new
    release = Queue.new

    holder = committed_data_thread(holder_pids) do
      TimekeepingOwnership.transaction do
        TimekeepingOwnership.lock("FOR UPDATE").find(TimekeepingOwnership::SINGLETON_ID)
        locked << true
        release.pop(timeout: 10)
      end
    end
    expect(locked.pop(timeout: 5)).to be(true)

    contender = committed_data_thread(contender_pids) do
      TimekeepingOwnership.where(id: TimekeepingOwnership::SINGLETON_ID).update_all(handoff_step: "close_admission")
    end

    begin
      blocked = blocked_by?(contender_pids.pop(timeout: 5), holder_pids.pop(timeout: 5))
    ensure
      release << true
    end

    expect(blocked).to be(true)
    expect(contender.join(5)).not_to be_nil
    expect(TimekeepingOwnership.find(TimekeepingOwnership::SINGLETON_ID).handoff_step).to eq("close_admission")
  ensure
    release&.push(true)
    [holder, contender].compact.each { |thread| thread.join(5) }
  end
end

RSpec.describe "Committed-data lock wait not yet started", committed_data: true do
  it "does not report a contender that has not sent its query as blocked, and gives up at its deadline" do
    holder_pids = Queue.new
    contender_pids = Queue.new
    locked = Queue.new
    release = Queue.new
    go = Queue.new

    holder = committed_data_thread(holder_pids) do
      TimekeepingOwnership.transaction do
        TimekeepingOwnership.lock("FOR UPDATE").find(TimekeepingOwnership::SINGLETON_ID)
        locked << true
        release.pop(timeout: 10)
      end
    end
    expect(locked.pop(timeout: 5)).to be(true)

    contender = committed_data_thread(contender_pids) do
      go.pop(timeout: 10)
      TimekeepingOwnership.where(id: TimekeepingOwnership::SINGLETON_ID).update_all(handoff_step: "close_admission")
    end
    contender_pid = contender_pids.pop(timeout: 5)
    holder_pid = holder_pids.pop(timeout: 5)

    begin
      # "These checks do not distinguish a database lock wait from a thread that has not reached its query."
      started = Process.clock_gettime(Process::CLOCK_MONOTONIC)
      before_query = blocked_by?(contender_pid, holder_pid, within: 0.3)
      elapsed = Process.clock_gettime(Process::CLOCK_MONOTONIC) - started

      go << true
      after_query = blocked_by?(contender_pid, holder_pid)
    ensure
      go << true
      release << true
    end

    expect(before_query).to be(false)
    expect(elapsed).to be < 2
    expect(after_query).to be(true)
  ensure
    go&.push(true)
    release&.push(true)
    [holder, contender].compact.each { |thread| thread.join(5) }
  end
end

