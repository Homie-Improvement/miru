# frozen_string_literal: true

require "rails_helper"
require Rails.root.join("db/migrate/20261020120000_drop_timesheet_entry_foreign_keys")

# Runs the migration's down and up inside the example's transaction, so every
# key it restores or drops is rolled back after the example.
RSpec.describe DropTimesheetEntryForeignKeys do
  let(:connection) { ActiveRecord::Base.connection }

  def run_migration(direction)
    ActiveRecord::Migration.suppress_messages { described_class.new.migrate(direction) }
  end

  # Matches the key on its column too, not only on the two tables.
  def dropped_key_validated?(key)
    connection.select_value(<<~SQL.squish)
      SELECT convalidated FROM pg_constraint
      WHERE contype = 'f'
        AND conrelid = #{connection.quote(key[:from_table].to_s)}::regclass
        AND confrelid = #{connection.quote(key[:to_table].to_s)}::regclass
        AND conkey = ARRAY[(SELECT attnum FROM pg_attribute
          WHERE attrelid = #{connection.quote(key[:from_table].to_s)}::regclass
            AND attname = #{connection.quote(key[:column].to_s)})]::smallint[]
    SQL
  end

  def restored_dropped_keys
    described_class::DROPPED_KEYS.select do |key|
      connection.foreign_key_exists?(key[:from_table], key[:to_table], column: key[:column])
    end
  end

  # Puts the database in the state the old body of this migration left: no keys.
  def remove_dropped_keys
    described_class::DROPPED_KEYS.each do |key|
      connection.remove_foreign_key key[:from_table], key[:to_table], column: key[:column], if_exists: true
    end
  end

  def expect_every_dropped_key_present_and_validated
    described_class::DROPPED_KEYS.each do |key|
      expect(connection.foreign_key_exists?(key[:from_table], key[:to_table], column: key[:column]))
        .to be(true), "expected #{key[:from_table]}.#{key[:column]} to keep its key"
      expect(dropped_key_validated?(key)).to be(true)
    end
  end

  it "stops the rollback before any change when a line item points at a missing entry" do
    remove_dropped_keys
    line_item = create(:invoice_line_item)
    missing_entry_id = TimesheetEntry.maximum(:id).to_i + 1_000
    connection.execute("UPDATE invoice_line_items SET timesheet_entry_id = #{missing_entry_id} WHERE id = #{line_item.id}")
    expect(restored_dropped_keys).to eq([])

    expect { run_migration(:down) }
      .to raise_error(described_class::DanglingReferencesError, /invoice_line_items\.timesheet_entry_id: 1/)
    expect(line_item.reload.timesheet_entry_id).to eq(missing_entry_id)
    expect(restored_dropped_keys).to eq([])
  end

  # A database that ran the old drop is restored with down; the next deploy's
  # db:prepare then runs up again, and that run must not take the keys away.
  it "restores the three keys, validated, on rollback" do
    remove_dropped_keys

    run_migration(:down)

    expect_every_dropped_key_present_and_validated

    run_migration(:up)

    expect_every_dropped_key_present_and_validated
  end

  it "leaves the keys absent, rather than re-adding them unvalidated, when up runs on a database that lost them" do
    remove_dropped_keys

    run_migration(:up)

    expect(restored_dropped_keys).to eq([])
    expect(connection.foreign_key_exists?(:timesheet_entries, :projects)).to be(true)
    expect(connection.foreign_key_exists?(:timesheet_entries, :users)).to be(true)
  end

  # Generated by Descant: acceptance tests below.

  # "Keep the database checks until every old application process has the replacement validations."
  # A deploy can re-run db:prepare; repeating up must still leave every key in place.
  it "up keeps all three timesheet entry keys, validated, on a database that still has them, however often it runs" do
    run_migration(:up)
    run_migration(:up)

    expect_every_dropped_key_present_and_validated
    expect(connection.foreign_key_exists?(:timesheet_entries, :projects)).to be(true)
    expect(connection.foreign_key_exists?(:timesheet_entries, :users)).to be(true)
  end

  # "Keep the database checks until every old application process has the replacement validations."
  # A database where the old drop removed only the first key before stopping must keep the other two,
  # and must not get the first one back unvalidated.
  it "keeps the remaining keys and does not re-add a missing one when up runs after a drop that stopped part-way" do
    link_key, line_item_key, agent_key = described_class::DROPPED_KEYS
    connection.remove_foreign_key link_key[:from_table], link_key[:to_table], column: link_key[:column]

    run_migration(:up)

    expect(restored_dropped_keys).to eq([line_item_key, agent_key])
    expect(dropped_key_validated?(line_item_key)).to be(true)
    expect(dropped_key_validated?(agent_key)).to be(true)
  end

  # "Keep the database checks until every old application process has the replacement validations."
  it "every key in DROPPED_KEYS is present in the loaded schema" do
    expected = [
      { from_table: :invoice_line_item_time_entries, to_table: :timesheet_entries, column: :timesheet_entry_id },
      { from_table: :invoice_line_items, to_table: :timesheet_entries, column: :timesheet_entry_id },
      { from_table: :timesheet_entries, to_table: :agents, column: :agent_id }
    ]
    expect(described_class::DROPPED_KEYS).to match_array(expected)

    # The test database is built from db/schema.rb, so this checks the schema declares the keys again.
    expect(restored_dropped_keys).to eq(described_class::DROPPED_KEYS)
  end

  # "Such a billing reference also trips the new rollback pre-check."
  it "refuses the rollback and changes nothing when a dangling agent and line item exist on a database that lost its keys" do
    remove_dropped_keys
    line_item = create(:invoice_line_item)
    entry = create(:timesheet_entry)
    missing_entry_id = TimesheetEntry.maximum(:id).to_i + 1_000
    missing_agent_id = Agent.maximum(:id).to_i + 1_000
    connection.execute("UPDATE invoice_line_items SET timesheet_entry_id = #{missing_entry_id} WHERE id = #{line_item.id}")
    connection.execute("UPDATE timesheet_entries SET agent_id = #{missing_agent_id} WHERE id = #{entry.id}")

    expect { run_migration(:down) }
      .to raise_error(described_class::DanglingReferencesError,
        /invoice_line_items\.timesheet_entry_id: 1.*timesheet_entries\.agent_id: 1/)

    expect(restored_dropped_keys).to eq([])
    expect(line_item.reload.timesheet_entry_id).to eq(missing_entry_id)
    expect(entry.reload.agent_id).to eq(missing_agent_id)
  end

  # "Such a billing reference also trips the new rollback pre-check."
  # Covers the two references the existing rollback example does not: the
  # line item time entry link and the entry's agent.
  it "stops the rollback and restores no key when a link row and an entry point at missing rows on a database that lost the keys" do
    remove_dropped_keys
    link = create(:invoice_line_item_time_entry)
    entry = create(:timesheet_entry)
    missing_entry_id = TimesheetEntry.maximum(:id).to_i + 1_000
    missing_agent_id = Agent.maximum(:id).to_i + 1_000
    connection.execute("UPDATE invoice_line_item_time_entries SET timesheet_entry_id = #{missing_entry_id} WHERE id = #{link.id}")
    connection.execute("UPDATE timesheet_entries SET agent_id = #{missing_agent_id} WHERE id = #{entry.id}")

    expect { run_migration(:down) }
      .to raise_error(described_class::DanglingReferencesError,
        /invoice_line_item_time_entries\.timesheet_entry_id: 1.*timesheet_entries\.agent_id: 1/)

    expect(link.reload.timesheet_entry_id).to eq(missing_entry_id)
    expect(entry.reload.agent_id).to eq(missing_agent_id)
    expect(restored_dropped_keys).to eq([])
  end
end
