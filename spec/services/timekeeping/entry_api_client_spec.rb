RSpec.describe Timekeeping::EntryApiClient, "write token role for an employee-first admin or owner" do
  let(:write_role_company) { create(:company) }
  let(:write_role_list_url) { %r{\Ahttp://timekeeping\.test/v1/companies/#{write_role_company.id}/entries} }
  let(:write_role_colleague) do
    create(:user).tap { |colleague| create(:employment, company: write_role_company, user: colleague) }
  end

  # Lists one user's entries with the read-token flag at the given value, and
  # returns the verified claims of the token sent. Without acting_user_id the
  # client mints the token for the listed user.
  def write_role_list(read_tokens_enabled, user_id:, **acting)
    tokens = []
    stub_request(:get, write_role_list_url).to_return do |request|
      tokens << request.headers["Authorization"].delete_prefix("Bearer ")
      { status: 200, body: { entries: [] }.to_json }
    end

    with_timekeeping_env(Timekeeping::UserToken::PRIVATE_KEY_ENV, timekeeping_key_pair.to_pem) do
      with_timekeeping_env(described_class::READ_TOKENS_ENV, read_tokens_enabled) do
        described_class.new(base_url: "http://timekeeping.test").list_entries(
          company_id: write_role_company.id, user_id:, from: Date.new(2026, 3, 1), to: Date.new(2026, 3, 31), **acting
        )
      end
    end
    Timekeeping::UserToken.verify(tokens.last, public_key: timekeeping_key_pair.public_key)
  end

  # "A write token for a user who holds employee first and admin or owner later in a company signs
  # the admin or owner role with purpose write"
  # The flag chooses only the purpose claim; the role is the same either way. The locked and billed
  # rules stay on the oldest company role, as the monolith's validations do, so primary_role stays employee.
  [
    [:admin, nil, :colleague, "write"],
    [:admin, "false", :colleague, "write"],
    [:admin, "true", :colleague, "read"],
    [:owner, nil, :colleague, "write"],
    [:owner, "false", :colleague, "write"],
    [:owner, "true", :colleague, "read"],
    [:admin, "false", :self, "write"]
  ].each do |privileged, read_tokens_enabled, listed, purpose|
    flag_label = read_tokens_enabled.nil? ? "unset" : read_tokens_enabled.inspect
    listed_label = listed == :self ? "their own entries" : "a colleague"

    it "signs #{privileged} with primary role employee and purpose #{purpose} for #{listed_label} " \
       "while the read-token flag is #{flag_label}" do
      # The employee role is added first so its roles row has the lower id in this company.
      actor = create(:user).tap do |user|
        create(:employment, company: write_role_company, user:)
        user.add_role(:employee, write_role_company)
        user.add_role(privileged, write_role_company)
      end

      claims =
        if listed == :self
          write_role_list(read_tokens_enabled, user_id: actor.id)
        else
          write_role_list(read_tokens_enabled, user_id: write_role_colleague.id, acting_user_id: actor.id)
        end

      expect([claims.user_id, claims.company_id, claims.role, claims.primary_role, claims.purpose])
        .to eq([actor.id, write_role_company.id, privileged.to_s, "employee", purpose])
      expect(actor.primary_role(write_role_company)).to eq("employee")
    end
  end
end

RSpec.describe Timekeeping::EntryApiClient, "read token role" do
  let(:read_role_company) { create(:company) }
  let(:read_role_list_url) { %r{\Ahttp://timekeeping\.test/v1/companies/#{read_role_company.id}/entries} }
  let(:read_role_colleague) do
    create(:user).tap { |colleague| create(:employment, company: read_role_company, user: colleague) }
  end

  def read_role_member
    create(:user).tap { |member| create(:employment, company: read_role_company, user: member) }
  end

  # Lists the colleague's entries for each actor with read tokens on, and
  # returns the entries of the last list with the verified claims of every
  # token sent.
  def read_role_list(actors, answer_entries: [])
    tokens = []
    stub_request(:get, read_role_list_url).to_return do |request|
      tokens << request.headers["Authorization"].delete_prefix("Bearer ")
      { status: 200, body: { entries: answer_entries }.to_json }
    end

    entries = with_timekeeping_env(Timekeeping::UserToken::PRIVATE_KEY_ENV, timekeeping_key_pair.to_pem) do
      with_timekeeping_env(described_class::READ_TOKENS_ENV, "true") do
        actors.map do |actor|
          described_class.new(base_url: "http://timekeeping.test").list_entries(
            company_id: read_role_company.id, user_id: read_role_colleague.id, from: Date.new(2026, 3, 1),
            to: Date.new(2026, 3, 31), acting_user_id: actor.id
          )
        end.last
      end
    end
    claims = tokens.map { |token| Timekeeping::UserToken.verify(token, public_key: timekeeping_key_pair.public_key) }
    [entries, claims]
  end

  # The employee role is added first, so it has the lower roles.id and sorts
  # first: the primary role says employee, while the index controllers let
  # this user read colleagues through has_role?(:admin, company).
  it "reads a colleague for an admin whose employee role is older with an admin read token for that company" do
    admin = read_role_member
    admin.add_role(:employee, read_role_company)
    admin.add_role(:admin, read_role_company)

    entries, claims = read_role_list([admin], answer_entries: [{ "id" => 5, "user_id" => read_role_colleague.id }])

    expect(entries).to eq([{ "id" => 5, "user_id" => read_role_colleague.id }])
    expect(WebMock).to have_requested(:get, read_role_list_url)
      .with(query: hash_including("user_id" => read_role_colleague.id.to_s))
    expect(claims.map { |claim| [claim.user_id, claim.company_id, claim.role, claim.purpose] })
      .to eq([[admin.id, read_role_company.id, "admin", "read"]])
    expect(admin.primary_role(read_role_company)).to eq("employee")
  end

  # The raised role must not widen a plain employee, nor a user whose admin
  # role is in another company.
  it "keeps the employee role on the read token for a plain employee or an admin of another company" do
    other_company = create(:company)
    plain_employee = read_role_member
    plain_employee.add_role(:employee, read_role_company)
    admin_elsewhere = read_role_member
    create(:employment, company: other_company, user: admin_elsewhere)
    admin_elsewhere.add_role(:admin, other_company)
    admin_elsewhere.add_role(:employee, read_role_company)

    _entries, claims = read_role_list([plain_employee, admin_elsewhere])

    expect(claims.map { |claim| [claim.user_id, claim.company_id, claim.role, claim.purpose] }).to eq(
      [
        [plain_employee.id, read_role_company.id, "employee", "read"],
        [admin_elsewhere.id, read_role_company.id, "employee", "read"]
      ]
    )
  end
end

RSpec.describe Timekeeping::EntryApiClient, "show_entry" do
  let(:show_company) { create(:company) }
  let(:show_admin) do
    create(:user).tap do |admin|
      create(:employment, company: show_company, user: admin)
      admin.add_role(:admin, show_company)
    end
  end
  let(:show_url) { "http://timekeeping.test/v1/companies/#{show_company.id}/entries/41" }

  def show_entry_call
    with_timekeeping_env(Timekeeping::UserToken::PRIVATE_KEY_ENV, timekeeping_key_pair.to_pem) do
      described_class.new(base_url: "http://timekeeping.test").show_entry(
        company_id: show_company.id, entry_id: 41, acting_user_id: show_admin.id, request_id: "req-show-1"
      )
    end
  end

  it "reads the entry for the acting user and sends the request id" do
    stub_request(:get, show_url).to_return(status: 200, body: { "id" => 41, "company_id" => show_company.id }.to_json)

    expect(show_entry_call).to eq("id" => 41, "company_id" => show_company.id)
    expect(WebMock).to have_requested(:get, show_url).with(headers: { "X-Request-Id" => "req-show-1" })
  end

  it "maps a missing entry to not found, a refused actor to forbidden and anything else to its own error" do
    raised = [404, 403, 401, 500].map do |status|
      stub_request(:get, show_url).to_return(status:, body: { reason: "detail" }.to_json)
      show_entry_call
    rescue StandardError => error
      error.class
    end

    expect(raised).to eq([ActiveRecord::RecordNotFound, Timekeeping::EntryWriteClient::Forbidden,
                          described_class::Error, described_class::Error])
  end
end
