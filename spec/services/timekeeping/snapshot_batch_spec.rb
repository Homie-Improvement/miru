RSpec.describe Timekeeping::SnapshotBatch do
  # "Read the jsonb payload from its raw text, so `duration` keeps its exact float bits and timestamps keep microseconds."
  # The receiving controller parses numbers as BigDecimal, so the delivered bits must survive this cast too.
  it "keeps the bits of a subnormal duration parsed as BigDecimal" do
    [5e-324, 0.1 + 0.2, 1.5].each do |duration|
      entry = TimekeepingSnapshots.entry(id: 11, company_id: 3, version: 2, project_id: 5, user_id: 7)
      batch = TimekeepingSnapshots.batch(TimekeepingSnapshots.item(entry, generation: 1, outbox_position: 1))
      parsed = JSON.parse(JSON.generate(batch).sub(/"duration":[^,}]+/, "\"duration\":#{duration}"),
                          decimal_class: BigDecimal)

      row = described_class.parse(parsed).sole.row

      expect([duration, [row.fetch("duration")].pack("G")]).to eq([duration, [duration].pack("G")])
    end
  end
end
