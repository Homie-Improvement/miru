RSpec.describe ClientPaymentMailer, "during a Timekeeping handoff", type: :mailer do
  # Acceptance bar: "Every invoice, line-item, invoice-tax and payment write, mobile-collection payments included,
  # gets 503 ownership_moving while handoff_step is set and writes nothing"
  it "refuses the client payment mail during a handoff without setting client_payment_sent_at or sending mail" do
    company = create(:company)
    client = create(:client, company:, email: "billing-client@example.com")
    invoice = create(:invoice, client:, company:)
    expect(invoice.reload.client_payment_sent_at).to be_nil
    TimekeepingOwnership.current.update!(handoff_step: "checkpoint")
    ActionMailer::Base.deliveries.clear

    expect do
      ClientPaymentMailer.with(invoice_id: invoice.id, subject: "Paid").payment.deliver_now
    end.to raise_error(Timekeeping::BillingFence::OwnershipMoving)

    expect(invoice.reload.client_payment_sent_at).to be_nil
    expect(ActionMailer::Base.deliveries).to be_empty
  end
end
