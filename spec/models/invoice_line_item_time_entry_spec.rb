RSpec.describe InvoiceLineItemTimeEntry, type: :model do
  it "refuses a join row to another company's entry, or to an entry with NULL company_id, with not found and no same-company message" do
    invoice = create(:invoice)
    invoice_line_item = create(:invoice_line_item, invoice:)
    other_company = create(:company)
    other_project = create(:project, client: create(:client, company: other_company), billable: true)
    other_user = create(:user, current_workspace: other_company)
    foreign_entry = create(:timesheet_entry, user: other_user, project: other_project, bill_status: "unbilled")
    own_project = create(:project, client: invoice.client, billable: true)
    own_user = create(:user, current_workspace: invoice.company)
    null_company_entry = create(:timesheet_entry, user: own_user, project: own_project, bill_status: "unbilled")
    # update_column skips the before_save that would fill company_id from the project again.
    null_company_entry.update_column(:company_id, nil)

    # "An entry id from another company gives not_found"
    # "A row whose `company_id` is NULL is not_found, never accepted for every company."
    [foreign_entry, null_company_entry.reload].each do |entry|
      link = build(:invoice_line_item_time_entry, invoice_line_item:, timesheet_entry: entry)

      expect(link).not_to be_valid
      expect(link.errors[:timesheet_entry]).to eq(["not found"])
      expect(link.errors.full_messages.join).not_to include("same company")
    end
  end
end
