RSpec.describe Agent, committed_data: true do
  # "A legacy detach nullifies agent_id under the legacy_gateway session mark after locking ownership and then the agent"
  it "a legacy agent destroy locks ownership then the agent, then nullifies entries under the legacy_gateway mark" do
    agent = create(:agent)
    project = create(:project, client: create(:client, company: agent.company))
    entry = create(:timesheet_entry, project:, user: agent.user, agent:)

    statements = []
    mark_at_update = nil
    reading = false
    subscription = ActiveSupport::Notifications.subscribe("sql.active_record") do |*, payload|
      next if reading

      sql = payload[:sql].to_s
      statements << sql
      if sql =~ /\AUPDATE "timesheet_entries"/i && sql.include?("agent_id")
        reading = true
        mark_at_update = ActiveRecord::Base.connection.select_value("SELECT current_setting('miru.writer', true)")
        reading = false
      end
    end
    begin
      agent.destroy!
    ensure
      ActiveSupport::Notifications.unsubscribe(subscription)
    end

    ownership_lock = statements.index { |sql| sql.include?("timekeeping_ownership") && sql.include?("FOR SHARE") }
    agent_lock = statements.index { |sql| sql.include?('FROM "agents"') && sql.include?("FOR UPDATE") }
    detach = statements.index { |sql| sql =~ /\AUPDATE "timesheet_entries"/i && sql.include?("agent_id") }

    expect([ownership_lock, agent_lock, detach]).to all(be_an(Integer))
    expect(ownership_lock).to be < agent_lock
    expect(agent_lock).to be < detach
    expect(mark_at_update).to eq("legacy_gateway")
    expect(entry.reload.agent_id).to be_nil
    expect(ActiveRecord::Base.connection.select_value("SELECT current_setting('miru.writer', true)").to_s).to eq("")
  end
end

