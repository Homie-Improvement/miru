# frozen_string_literal: true

require "rails_helper"
require "yaml"
require "erb"

RSpec.describe "Solid Queue schedule" do
  let(:config) do
    YAML.safe_load(
      ERB.new(Rails.root.join("config/solid_queue.yml").read).result,
      aliases: true
    )
  end

  it "runs daily Stripe subscription reconciliation in default and production" do
    default_task = config.dig("default", "dispatchers", 0, "recurring_tasks", "sync_stripe_subscriptions")
    production_task = config.dig("production", "dispatchers", 0, "recurring_tasks", "sync_stripe_subscriptions")

    expect(default_task).to include(
      "class" => "SyncStripeSubscriptionsJob",
      "schedule" => "0 1 * * *"
    )
    expect(production_task).to include(
      "class" => "SyncStripeSubscriptionsJob",
      "schedule" => "0 1 * * *"
    )
  end

  it "runs monthly report delivery on the first day of the month in default and production" do
    default_task = config.dig("default", "dispatchers", 0, "recurring_tasks", "monthly_reports_delivery")
    production_task = config.dig("production", "dispatchers", 0, "recurring_tasks", "monthly_reports_delivery")

    expect(default_task).to include(
      "class" => "MonthlyReportsDeliveryJob",
      "schedule" => "0 14 1 * * Asia/Kolkata"
    )
    expect(production_task).to include(
      "class" => "MonthlyReportsDeliveryJob",
      "schedule" => "0 14 1 * * Asia/Kolkata"
    )
  end

  it "runs analytics threshold notifications weekly on Monday at 1 AM Eastern" do
    default_task = config.dig("default", "dispatchers", 0, "recurring_tasks", "analytics_threshold_notifications")
    production_task = config.dig("production", "dispatchers", 0, "recurring_tasks", "analytics_threshold_notifications")

    expect(default_task).to include(
      "class" => "Analytics::ThresholdNotificationsJob",
      "schedule" => "0 1 * * 1 America/New_York"
    )
    expect(production_task).to include(
      "class" => "Analytics::ThresholdNotificationsJob",
      "schedule" => "0 1 * * 1 America/New_York"
    )
  end

  it "runs database backups every 30 minutes in production by default" do
    production_task = config.dig("production", "dispatchers", 0, "recurring_tasks", "database_backup")

    expect(production_task).to include(
      "class" => "DatabaseBackupJob",
      "schedule" => "*/30 * * * *"
    )
  end

  # Generated by Descant: acceptance tests below.

  # "Add an `invoice_operations` worker block in both the `default` and `production` sections, mirroring `billing_sync`, plus a recurring task under `dispatchers.recurring_tasks` in both."
  it "configures an invoice_operations worker and a recurring recovery task in default and production" do
    %w[default production].each do |section|
      worker = config.dig(section, "workers").find { |block| block["queues"] == "invoice_operations" }
      expect(worker).to include("processes" => 1, "threads" => 1)
      expect(worker["polling_interval"]).to be_present

      task = config.dig(section, "dispatchers", 0, "recurring_tasks").values
        .find { |entry| entry["class"] == "RecoverInvoiceOperationIntentsJob" }
      expect(task).to be_present
      expect(task["schedule"]).to be_present
    end
  end

  # "config/solid_queue.yml runs a timekeeping_relay worker with one thread and one process in every block that
  # has billing_sync, and Timekeeping::RelayJob is queued on timekeeping_relay"
  it "runs a single-thread single-process timekeeping_relay worker and a 10-second RelayJob task in every block with billing_sync" do
    blocks = config.select do |_name, block|
      block.is_a?(Hash) && Array(block["workers"]).any? { |worker| worker["queues"] == "billing_sync" }
    end
    expect(blocks.keys).to include("default", "production")

    blocks.each do |name, block|
      relay_workers = block["workers"].select { |worker| worker["queues"] == "timekeeping_relay" }
      expect([name, relay_workers.size]).to eq([name, 1])
      expect([name, relay_workers.first.slice("threads", "processes")])
        .to eq([name, { "threads" => 1, "processes" => 1 }])

      tasks = block.dig("dispatchers", 0, "recurring_tasks").values.select { |task| task["class"] == "Timekeeping::RelayJob" }
      expect([name, tasks.map { |task| task["schedule"] }]).to eq([name, ["every 10 seconds"]])
    end
  end
end
