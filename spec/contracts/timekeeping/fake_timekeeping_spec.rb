RSpec.describe TimekeepingContract::FakeTimekeeping, "in token mode on detach-entries" do
  let(:detach_token_fake) { described_class.new(token_public_key: timekeeping_key_pair.public_key) }
  let(:detach_company_id) { 41 }
  let(:detach_path) { "/v1/companies/#{detach_company_id}/agents/9/detach-entries" }

  def detach_token_status(token)
    detach_token_fake.call(
      "POST", detach_path,
      headers: { "Authorization" => "Bearer #{token}" },
      body: { "operation_id" => SecureRandom.uuid, "generation" => detach_token_fake.generation }
    ).status
  end

  # "Make the fake (`spec/support/timekeeping/fake_timekeeping.rb`) check a service token's operations against `BACKGROUND_OPERATIONS`."
  # "The token's operations are exactly `[\"agents.detach_entries\"]`, each one is in `BACKGROUND_OPERATIONS`, and the fake refuses a token naming `detach_entries`."
  it "token mode detach-entries accepts only a service token for the path company naming agents.detach_entries" do
    mint = lambda do |company_id:, operations:, private_key: timekeeping_key_pair|
      Timekeeping::ServiceToken.mint(company_id:, operations:, private_key:)
    end
    now = Time.current.to_i
    shared_secret = SecureRandom.hex(32)
    hmac_token = JWT.encode(
      { typ: "timekeeping_service", sub: "forged", company_id: detach_company_id,
        operations: ["agents.detach_entries"], iat: now, exp: now + 60, jti: SecureRandom.uuid },
      shared_secret, "HS256"
    )

    expect(detach_token_status(mint.call(company_id: detach_company_id, operations: ["detach_entries"]))).to eq(403)
    expect(detach_token_status(mint.call(company_id: detach_company_id + 1,
                                         operations: ["agents.detach_entries"]))).to eq(404)
    expect(detach_token_status(mint.call(company_id: detach_company_id, operations: ["agents.detach_entries"],
                                         private_key: OpenSSL::PKey::RSA.generate(2048)))).to eq(401)
    expect(detach_token_status(hmac_token)).to eq(401)
    expect(detach_token_status(shared_secret)).to eq(401)
    expect(detach_token_status(mint.call(company_id: detach_company_id,
                                         operations: ["agents.detach_entries"]))).to eq(200)
  end
end

RSpec.describe TimekeepingContract::FakeTimekeeping, "service tokens bound to one company" do
  let(:tenant_fake) { described_class.new(token_public_key: timekeeping_key_pair.public_key) }

  it "refuses a detach-entries service token bound to another company and leaves that company's entries attached" do
    path_company = create(:company)
    token_company = create(:company)
    user = create(:user, current_workspace_id: path_company.id)
    project = create(:project, client: create(:client, company: path_company))
    agent_id = tenant_fake.add_agent(company_id: path_company.id, user_id: user.id)
    entry = tenant_fake.add_entry(company_id: path_company.id, user_id: user.id, project_id: project.id, agent_id:)

    # "The forwarded call uses a token bound to the agent's company that grants only agents.detach_entries, never TIMEKEEPING_SERVICE_TOKEN"
    # A token for another company must not reach this company's entries, even when it names the right operation.
    token = Timekeeping::ServiceToken.mint(company_id: token_company.id, operations: ["agents.detach_entries"],
                                           private_key: timekeeping_key_pair)
    response = tenant_fake.call(
      "POST", "/v1/companies/#{path_company.id}/agents/#{agent_id}/detach-entries",
      headers: { "Authorization" => "Bearer #{token}" },
      body: { "operation_id" => SecureRandom.uuid, "generation" => tenant_fake.generation }
    )

    expect(response.status).to eq(404)
    expect(tenant_fake.stored_entry(entry.fetch("id"))["agent_id"]).to eq(agent_id)
  end
end

