RSpec.describe "timekeeping handoff tasks" do
  before(:all) do
    Rails.application.load_tasks if Rake::Task.tasks.empty?
  end

  around do |example|
    direction_before = ENV["DIRECTION"]
    example.run
  ensure
    ENV["DIRECTION"] = direction_before
  end

  def invoke_handoff_task(name)
    Rake::Task[name].reenable
    Rake::Task[name].invoke
  end

  it "handoff tasks pass their direction and abort flag to the runner and refuse a missing or unknown DIRECTION" do
    # "Add rake tasks for cutover, rollback, re-cutover, resume and abort to `lib/tasks/timekeeping.rake`, next to the existing tasks. They check input and call the runner."
    runner = Timekeeping::Handoff::Runner
    expect(runner).to receive(:run).with(hash_including(direction: :cutover)).ordered
    expect(runner).to receive(:run).with(hash_including(direction: :rollback)).ordered
    expect(runner).to receive(:run).with(hash_including(direction: :re_cutover)).ordered
    expect(runner).to receive(:run).with(hash_including(direction: :cutover, abort: true)).ordered

    invoke_handoff_task("timekeeping:handoff_cutover")
    invoke_handoff_task("timekeeping:handoff_rollback")
    invoke_handoff_task("timekeeping:handoff_re_cutover")
    ENV["DIRECTION"] = "cutover"
    invoke_handoff_task("timekeeping:handoff_abort")

    ENV.delete("DIRECTION")
    expect { invoke_handoff_task("timekeeping:handoff_resume") }.to raise_error(SystemExit).and output(/DIRECTION/).to_stderr
    ENV["DIRECTION"] = "sideways"
    expect { invoke_handoff_task("timekeeping:handoff_resume") }.to raise_error(SystemExit).and output(/DIRECTION|sideways/).to_stderr
  end

  # Only handoff_resume continues a handoff or re-sends the admit call after a flip; the forward tasks start one.
  it "forward handoff tasks pass resume: false and handoff_resume passes resume: true" do
    runner = Timekeeping::Handoff::Runner
    expect(runner).to receive(:run).with(direction: :cutover, resume: false).ordered
    expect(runner).to receive(:run).with(direction: :rollback, resume: false).ordered
    expect(runner).to receive(:run).with(direction: :re_cutover, resume: false).ordered
    expect(runner).to receive(:run).with(direction: :rollback, resume: true).ordered

    invoke_handoff_task("timekeeping:handoff_cutover")
    invoke_handoff_task("timekeeping:handoff_rollback")
    invoke_handoff_task("timekeeping:handoff_re_cutover")
    ENV["DIRECTION"] = "rollback"
    expect { invoke_handoff_task("timekeeping:handoff_resume") }.to output(/rollback finished/).to_stdout
  end
end
