RSpec.describe "RackAttack auth throttles", type: :request do
  let(:ip_address) { "203.0.113.10" }
  let(:json_headers) { { "CONTENT_TYPE" => "application/json", "REMOTE_ADDR" => ip_address } }

  # A fresh store per example keeps counters from other specs out of these
  # examples, and restoring both values keeps them from changing later specs.
  # Freezing time keeps every request in one rack-attack period, which is keyed
  # on Time.now.to_i / period, so a burst cannot straddle a minute boundary.
  around do |example|
    enabled = Rack::Attack.enabled
    store = Rack::Attack.cache.store
    Rack::Attack.enabled = true
    Rack::Attack.cache.store = ActiveSupport::Cache::MemoryStore.new

    freeze_time { example.run }
  ensure
    Rack::Attack.enabled = enabled
    Rack::Attack.cache.store = store
  end

  # Signup checks the password against the breached-password service. Request
  # specs allow real HTTP, so without this stub each signup here would wait on
  # that service from any runner with network access.
  before do
    allow(Pwned::Password).to receive(:new).and_return(instance_double(Pwned::Password, pwned_count: 0))
  end

  it "throttles repeated login attempts from the same ip" do
    20.times do
      post api_v1_users_login_path,
        params: { user: { email: "missing@example.com", password: "bad-password" } }.to_json,
        headers: json_headers

      expect(response).to have_http_status(:unprocessable_entity)
    end

    post api_v1_users_login_path,
      params: { user: { email: "missing@example.com", password: "bad-password" } }.to_json,
      headers: json_headers

    expect(response).to have_http_status(:too_many_requests)
    expect(response.parsed_body["error"]).to eq("Too many requests. Please try again later.")
  end

  it "throttles repeated recovery requests from the same ip" do
    10.times do
      post api_v1_users_forgot_password_path,
        params: { user: { email: "missing@example.com" } }.to_json,
        headers: json_headers

      expect(response).to have_http_status(:ok)
    end

    post api_v1_users_forgot_password_path,
      params: { user: { email: "missing@example.com" } }.to_json,
      headers: json_headers

    expect(response).to have_http_status(:too_many_requests)
    expect(response.parsed_body["error"]).to eq("Too many requests. Please try again later.")
  end

  it "throttles repeated signup attempts from the same ip" do
    payload = {
      user: {
        email: "invalid",
        first_name: "Rate",
        last_name: "Limited",
        password: "Password123!",
        password_confirmation: "Password123!"
      }
    }.to_json

    5.times do
      post api_v1_users_signup_path, params: payload, headers: json_headers
      expect(response).to have_http_status(:unprocessable_entity)
    end

    post api_v1_users_signup_path, params: payload, headers: json_headers

    expect(response).to have_http_status(:too_many_requests)
  end
end

# Generated by Descant: acceptance tests below.
RSpec.describe "RackAttack signup throttle", type: :request do
  let(:signup_limit_ip) { "203.0.113.10" }
  let(:invalid_signup_limit_payload) { signup_limit_payload_for("invalid") }

  def signup_limit_payload_for(email)
    {
      user: {
        email:,
        first_name: "Rate",
        last_name: "Limited",
        password: "Password123!",
        password_confirmation: "Password123!"
      }
    }.to_json
  end

  def post_signup_limit_from(ip, payload = invalid_signup_limit_payload)
    post api_v1_users_signup_path,
      params: payload,
      headers: { "CONTENT_TYPE" => "application/json", "REMOTE_ADDR" => ip }
  end

  def use_up_signup_limit
    5.times do
      post_signup_limit_from(signup_limit_ip)
      expect(response).to have_http_status(:unprocessable_content)
    end
  end

  around do |example|
    enabled = Rack::Attack.enabled
    store = Rack::Attack.cache.store
    Rack::Attack.enabled = true
    Rack::Attack.cache.store = ActiveSupport::Cache::MemoryStore.new

    example.run
  ensure
    Rack::Attack.enabled = enabled
    Rack::Attack.cache.store = store
  end

  context "with the clock frozen" do
    around do |example|
      freeze_time { example.run }
    end

    it "answers the sixth signup and its retry from one ip with 429, creating no user, while another ip still reaches signup" do
      use_up_signup_limit

      # "expected the response to have status code :too_many_requests (429) but it was :unprocessable_content (422)"
      expect { post_signup_limit_from(signup_limit_ip) }.not_to change(User, :count)
      expect(response).to have_http_status(:too_many_requests)
      expect(response.parsed_body).to eq("error" => "Too many requests. Please try again later.")

      # Retrying after the block must not reset the counter or slip through to signup.
      expect { post_signup_limit_from(signup_limit_ip) }.not_to change(User, :count)
      expect(response).to have_http_status(:too_many_requests)

      # The rule is keyed on the request IP, so another address still reaches signup.
      post_signup_limit_from("198.51.100.20")
      expect(response).to have_http_status(:unprocessable_content)
    end

    it "answers a valid sixth signup from a throttled ip with 429 and stores no user, and keeps answering 429 on retry" do
      use_up_signup_limit

      # The throttle must answer before the signup controller runs, so even a
      # valid signup over the limit leaves no account behind.
      valid_payload = signup_limit_payload_for("throttled-signup@example.com")
      2.times do
        expect { post_signup_limit_from(signup_limit_ip, valid_payload) }.not_to change(User, :count)
        expect(response).to have_http_status(:too_many_requests)
        expect(response.parsed_body["error"]).to eq("Too many requests. Please try again later.")
      end

      expect(User.exists?(email: "throttled-signup@example.com")).to be(false)
    end
  end

  it "answers the sixth signup with 429 even when the burst starts one second before a minute boundary" do
    # rack-attack keys its counter on Time.now.to_i / period; with the clock frozen,
    # a burst that starts at hh:mm:59 must still be counted in one period.
    travel_to(Time.zone.parse("2026-01-01 10:00:59"))
    freeze_time do
      use_up_signup_limit

      post_signup_limit_from(signup_limit_ip)
      expect(response).to have_http_status(:too_many_requests)
      expect(response.parsed_body["error"]).to eq("Too many requests. Please try again later.")
    end
  end

  it "counts signups from zero after an earlier spec left a used store and restores that store and disabled state afterwards" do
    original_enabled = Rack::Attack.enabled
    original_store = Rack::Attack.cache.store

    # State an earlier spec in the same process could leave behind: throttling
    # switched off and a store that already holds counters.
    leftover_store = ActiveSupport::Cache::MemoryStore.new
    leftover_store.write("leftover:auth/signup/ip:203.0.113.10", 99)
    Rack::Attack.enabled = false
    Rack::Attack.cache.store = leftover_store

    begin
      saved_enabled = Rack::Attack.enabled
      saved_store = Rack::Attack.cache.store
      Rack::Attack.enabled = true
      Rack::Attack.cache.store = ActiveSupport::Cache::MemoryStore.new

      begin
        freeze_time do
          use_up_signup_limit

          post_signup_limit_from(signup_limit_ip)
          expect(response).to have_http_status(:too_many_requests)
        end
      ensure
        Rack::Attack.enabled = saved_enabled
        Rack::Attack.cache.store = saved_store
      end

      expect(Rack::Attack.enabled).to be(false)
      expect(Rack::Attack.cache.store).to equal(leftover_store)
      expect(leftover_store.read("leftover:auth/signup/ip:203.0.113.10")).to eq(99)
    ensure
      Rack::Attack.enabled = original_enabled
      Rack::Attack.cache.store = original_store
    end
  end
end
