      }]
    }
    paypal = instance_double(PaymentProviders::PaypalClient)
    allow(PaymentProviders::PaypalClient).to receive(:new).with(provider:).and_return(paypal)
    allow(paypal).to receive(:verify_webhook_signature).and_return(true)
    allow(paypal).to receive(:show_order).with("ORDER-1").and_return(completed_order)
    allow(paypal).to receive(:capture_order)
    allow(PaymentMailer).to receive_message_chain(:with, :payment, :deliver_later)
    allow_any_instance_of(Invoice).to receive(:send_to_client_email)
    payload = {
      id: "WH-EVT-REPLAY",
      event_type: "PAYMENT.CAPTURE.COMPLETED",
      resource: { id: "CAP-REPLAY", status: "COMPLETED", custom_id: invoice.id.to_s, supplementary_data: { related_ids: { order_id: "ORDER-1" } } }
    }.to_json
    headers = {
      "CONTENT_TYPE" => "application/json",
      "PAYPAL-TRANSMISSION-ID" => "tid",
      "PAYPAL-TRANSMISSION-SIG" => "sig",
      "PAYPAL-TRANSMISSION-TIME" => "2026-09-12T10:00:00Z",
      "PAYPAL-CERT-URL" => "https://api.sandbox.paypal.com/cert",
      "PAYPAL-AUTH-ALGO" => "SHA256withRSA"
    }

    TimekeepingOwnership.current.update!(handoff_step: "settle")
    expect(Payment.where(invoice_id: invoice.id).count).to eq(0)
    expect(invoice.reload).to have_attributes(status: "sent", amount_due: 100)

    post "/webhooks/paypal/events", params: payload, headers: headers

    expect(response).to have_http_status(:service_unavailable)
    expect(JSON.parse(response.body)["reason"]).to eq("ownership_moving")
    expect(Payment.where(invoice_id: invoice.id).count).to eq(0)
    expect(invoice.reload).to have_attributes(status: "sent", amount_due: 100)

