    allow(paypal_client).to receive(:capture_order)
    payload = {
      id: "WH-EVT-BAD-SIG",
      event_type: "PAYMENT.CAPTURE.COMPLETED",
      resource: { id: "CAP-1", status: "COMPLETED", custom_id: invoice.id.to_s, supplementary_data: { related_ids: { order_id: "ORDER-1" } } }
    }.to_json
    TimekeepingOwnership.current.update!(handoff_step: "settle")
    expect(Payment.where(invoice_id: invoice.id).count).to eq(0)

    post "/webhooks/paypal/events", params: payload, headers: {
      "CONTENT_TYPE" => "application/json",
      "PAYPAL-TRANSMISSION-ID" => "tid",
      "PAYPAL-TRANSMISSION-SIG" => "forged",
      "PAYPAL-TRANSMISSION-TIME" => "2026-09-12T10:00:00Z",
      "PAYPAL-CERT-URL" => "https://api.sandbox.paypal.com/cert",
      "PAYPAL-AUTH-ALGO" => "SHA256withRSA"
    }

    # "Verify valid events return ownership_moving without writes, invalid signatures retain their existing response, and replay succeeds after handoff."
    # The signature is checked before the billing fence, so an unsigned caller
    # gets the same 401 as outside a handoff and cannot probe the handoff state.
    expect(response).to have_http_status(:unauthorized)
    expect(response.body).not_to include("ownership_moving")
    expect(response.body).not_to include("settle")
    expect(response.headers["Retry-After"]).to be_nil
    expect(paypal_client).to have_received(:verify_webhook_signature)
    expect(paypal_client).not_to have_received(:show_order)
    expect(paypal_client).not_to have_received(:capture_order)
    expect(Payment.where(invoice_id: invoice.id).count).to eq(0)
    expect(invoice.reload.status).to eq("sent")
  end
end

