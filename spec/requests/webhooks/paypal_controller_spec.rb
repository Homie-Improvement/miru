    post "/webhooks/paypal/events", params: payload, headers: headers

    expect(response).to have_http_status(:ok)
    expect(Payment.where(invoice_id: invoice.id).count).to eq(1)
    expect(Payment.find_by(invoice_id: invoice.id).provider_event_id).to eq("paypal:CAP-REPLAY")
    expect(invoice.reload).to have_attributes(status: "paid", amount_due: 0)

    # PayPal redelivers an event it already got a 200 for; the second delivery must not pay twice.
    post "/webhooks/paypal/events", params: payload, headers: headers

    expect(response).to have_http_status(:ok)
    expect(Payment.where(invoice_id: invoice.id).count).to eq(1)
    expect(paypal).not_to have_received(:capture_order)
  end
end

