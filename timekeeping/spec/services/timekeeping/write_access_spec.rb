RSpec.describe Timekeeping::WriteAccess do
  # A read token may carry a raised admin role for a multi-role user; writes
  # must keep the primary role, so only a write-purpose (or pre-change,
  # purpose-less) token may write. Any other purpose is refused, never skipped.
  it "forbids writes for a read-purpose or unknown-purpose token and keeps allowing write-purpose and purpose-less tokens" do
    identity_with = lambda do |purpose|
      Timekeeping::Identity.new(kind: :user, status: :verified, user_id: 7, company_id: 1, role: "admin", purpose:)
    end

    expect(described_class.decide(identity_with.call("read"), path_company_id: "1")).to eq(:forbidden)
    expect(described_class.decide(identity_with.call("bogus"), path_company_id: "1")).to eq(:forbidden)
    expect(described_class.decide(identity_with.call("write"), path_company_id: "1")).to eq(:allowed)
    expect(described_class.decide(identity_with.call(nil), path_company_id: "1")).to eq(:allowed)
    expect(described_class.decide(identity_with.call("write"), path_company_id: "2")).to eq(:not_found)
  end
end

RSpec.describe Timekeeping::WriteAccess do
  it "never allows a write to another company's path, whatever the token purpose" do
    write_admin = Timekeeping::Identity.new(kind: :user, status: :verified, user_id: 7, company_id: 1, role: "admin",
                                            purpose: "write")
    read_admin = Timekeeping::Identity.new(kind: :user, status: :verified, user_id: 7, company_id: 1, role: "admin",
                                           purpose: "read")

    expect(described_class.decide(write_admin, path_company_id: "2")).to eq(:not_found)
    expect(described_class.decide(read_admin, path_company_id: "2")).not_to eq(:allowed)
    expect(described_class.decide(read_admin, path_company_id: "1")).to eq(:forbidden)
  end
end

RSpec.describe Timekeeping::WriteAccess, "token purpose" do
  it "forbids a write for any token purpose other than write or absent" do
    decisions = [nil, "write", "read", "bogus", ""].map do |purpose|
      identity = Timekeeping::Identity.new(kind: :user, status: :verified, user_id: 7, company_id: 1, role: "admin",
                                           purpose:)
      [purpose, described_class.decide(identity, path_company_id: "1")]
    end

    expect(decisions).to eq(
      [[nil, :allowed], ["write", :allowed], ["read", :forbidden], ["bogus", :forbidden], ["", :forbidden]]
    )
  end
end

