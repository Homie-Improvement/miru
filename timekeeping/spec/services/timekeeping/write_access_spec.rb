RSpec.describe Timekeeping::WriteAccess do
  # Tokens minted by a monolith that does not yet sign a purpose carry the primary role, as before,
  # so the read/write split must not refuse them during a deploy. A read token on another company's
  # path still answers not_found, not forbidden, so the company check keeps its order.
  it "still allows a write-purpose or purpose-less token signed before the purpose claim existed" do
    write_token = Timekeeping::Identity.new(kind: :user, status: :verified, user_id: 7, company_id: 1, role: "employee",
                                            purpose: "write")
    legacy_token = Timekeeping::Identity.new(kind: :user, status: :verified, user_id: 7, company_id: 1, role: "employee")
    read_token = Timekeeping::Identity.new(kind: :user, status: :verified, user_id: 7, company_id: 1, role: "admin",
                                           purpose: "read")

    expect(described_class.decide(write_token, path_company_id: "1")).to eq(:allowed)
    expect(described_class.decide(legacy_token, path_company_id: "1")).to eq(:allowed)
    expect(described_class.decide(read_token, path_company_id: "1")).to eq(:forbidden)
  end
end
