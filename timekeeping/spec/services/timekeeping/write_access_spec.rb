# frozen_string_literal: true

require "rails_helper"

RSpec.describe Timekeeping::WriteAccess do
  let(:user) { Timekeeping::Identity.new(kind: :user, status: :verified, user_id: 7, company_id: 1, role: "employee") }

  it "allows a verified user on their own company's path" do
    expect(described_class.decide(user, path_company_id: "1")).to eq(:allowed)
  end

  it "answers reference_unavailable for an expired token, whatever the path company" do
    expired = Timekeeping::Identity.anonymous(:expired)

    %w[1 2 abc].push(nil).each do |path_company_id|
      expect(described_class.decide(expired, path_company_id:)).to eq(:reference_unavailable)
    end
  end

  it "answers unauthorized for a missing or invalid token and for the service identity" do
    [
      Timekeeping::Identity.anonymous(:missing),
      Timekeeping::Identity.anonymous(:invalid),
      Timekeeping::Identity.service
    ].each do |identity|
      expect(described_class.decide(identity, path_company_id: "1")).to eq(:unauthorized)
    end
  end

  it "answers not_found for a verified user on another company's path" do
    expect(described_class.decide(user, path_company_id: "2")).to eq(:not_found)
  end
end

# Generated by Descant: acceptance tests below.
RSpec.describe Timekeeping::WriteAccess, "token purpose" do
  def write_access_identity_with_purpose(purpose, role: "admin")
    Timekeeping::Identity.new(kind: :user, status: :verified, user_id: 7, company_id: 1, role:, purpose:)
  end

  # A read token may carry a raised admin role for a multi-role user, so only
  # a write token, or one signed before purposes existed, may write. Any other
  # purpose is refused, never skipped.
  it "forbids a write for any token purpose other than write or absent" do
    decisions = [nil, "write", "read", "bogus", "", "READ"].map do |purpose|
      [purpose, described_class.decide(write_access_identity_with_purpose(purpose), path_company_id: "1")]
    end

    expect(decisions).to eq(
      [[nil, :allowed], ["write", :allowed], ["read", :forbidden], ["bogus", :forbidden], ["", :forbidden],
       ["READ", :forbidden]]
    )
  end

  # Tokens minted before the purpose claim existed carry the primary role, as
  # before, so the read/write split must not refuse them during a deploy.
  it "still allows an employee token built without a purpose or with a write purpose" do
    legacy_token = Timekeeping::Identity.new(kind: :user, status: :verified, user_id: 7, company_id: 1, role: "employee")

    expect(described_class.decide(legacy_token, path_company_id: "1")).to eq(:allowed)
    expect(described_class.decide(write_access_identity_with_purpose("write", role: "employee"), path_company_id: "1"))
      .to eq(:allowed)
  end

  # The company check keeps its order: another company's path answers
  # not_found, whatever the purpose.
  it "never allows a write to another company's path, whatever the token purpose" do
    %w[write read].each do |purpose|
      expect(described_class.decide(write_access_identity_with_purpose(purpose), path_company_id: "2")).to eq(:not_found)
    end
  end
end
