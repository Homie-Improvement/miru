RSpec.describe "Timekeeping internal write metrics while a window row is held" do
  self.use_transactional_tests = false

  let(:held_row_metrics_token) { "service-#{SecureRandom.hex(24)}" }

  around do |example|
    with_timekeeping_env(
      Timekeeping::Environment::TOKEN_PUBLIC_KEY => rsa_key_pair.public_key.to_pem,
      Timekeeping::Environment::SERVICE_TOKEN => held_row_metrics_token
    ) { example.run }
  end

  after { ApplicationRecord.connection.execute("TRUNCATE write_metric_windows, write_metric_events") }

  def held_row_metric_writes
    get "/internal/v1/metrics", headers: { "Authorization" => "Bearer #{held_row_metrics_token}" }
    writes = response.parsed_body.fetch("companies").to_h do |company|
      [company["company_id"], company["windows"].sum { |window| window["writes"] }]
    end
    [response.status, writes]
  end

  # "treat response delivery independently from metric persistence as follow-up
  # work that preserves counts rather than discarding timed-out events."
  it "answers metrics while one company's window row is held, keeps that company's pending write, and counts it on the next read" do
    stub_const("Timekeeping::WriteMetrics::LOCK_TIMEOUT_MS", 1000)
    at = Time.utc(2026, 3, 3, 12, 0, 10)
    record = ->(company_id) { Timekeeping::WriteMetrics.new(clock: -> { at }).record(company_id:, outcome: :write, latency_ms: 40) }
    record.call(1)
    Timekeeping::WriteMetrics.fold_pending
    record.call(1)
    record.call(2)

    held = Queue.new
    release = Queue.new
    holder_pid = Queue.new
    holder = Thread.new do
      ApplicationRecord.connection_pool.with_connection do |connection|
        holder_pid << connection.select_value("SELECT pg_backend_pid()")
        connection.transaction do
          connection.execute("SELECT 1 FROM write_metric_windows WHERE company_id = 1 FOR UPDATE")
          held << true
          release.pop(timeout: 10)
        end
      end
    end
    expect(held.pop(timeout: 10)).to be(true)
    pid = holder_pid.pop(timeout: 10)

    # Polls until some other session reports waiting on the holder's lock.
    watcher = Thread.new do
      ApplicationRecord.connection_pool.with_connection do |connection|
        deadline = Process.clock_gettime(Process::CLOCK_MONOTONIC) + 5
        seen = false
        until seen || Process.clock_gettime(Process::CLOCK_MONOTONIC) > deadline
          seen = connection.select_value(ApplicationRecord.sanitize_sql_array(
            ["SELECT EXISTS (SELECT 1 FROM pg_stat_activity WHERE ? = ANY(pg_blocking_pids(pid)))", pid]
          ))
          sleep 0.02 unless seen
        end
        seen
      end
    end

    status_while_held, writes_while_held = held_row_metric_writes
    blocked = watcher.join(10)&.value
    release << true
    holder.join(10)

    expect(blocked).to be(true), "the metrics read never waited on the held window row"
    expect([status_while_held, writes_while_held]).to eq([200, { 1 => 1, 2 => 1 }])
    expect(held_row_metric_writes).to eq([200, { 1 => 2, 2 => 1 }])
    expect(WriteMetricEvent.count).to eq(0)
  end
end
