      Timekeeping::Environment::SERVICE_TOKEN => held_row_service_token
    ) { example.run }
  end

  def held_row_company_writes
    get "/internal/v1/metrics", headers: { "Authorization" => "Bearer #{held_row_service_token}" }
    [response.status, response.parsed_body.fetch("companies").to_h do |company|
      [company["company_id"], company["windows"].sum { |window| window["writes"] }]
    end]
  end

  # The issue asks for work that "preserves counts rather than discarding timed-out events":
  # the metrics read must not lose a write whose fold met a held row, and must show it once the row is free.
  it "answers 200 while a company's window row is held and reports that company's kept write on the read after release" do
    stub_const("Timekeeping::WriteMetrics::LOCK_TIMEOUT_MS", 200)
    metrics = Timekeeping::WriteMetrics.new(clock: -> { Time.utc(2026, 3, 3, 12, 2) })
    metrics.record(company_id: 7, outcome: :write, latency_ms: 40)
    expect(held_row_company_writes).to eq([200, { 7 => 1 }])

    held = Queue.new
    release = Queue.new
    holder = Thread.new do
      ApplicationRecord.connection_pool.with_connection do |connection|
        connection.transaction do
          connection.execute("SELECT 1 FROM write_metric_windows WHERE company_id = 7 FOR UPDATE")
          held << true
          release.pop
        end
      end
    end
    begin
      expect(held.pop(timeout: 10)).to be(true)
      metrics.record(company_id: 7, outcome: :write, latency_ms: 40)
      expect(held_row_company_writes).to eq([200, { 7 => 1 }])
    ensure
      release << true
      holder.join(10)
    end

    expect(held_row_company_writes).to eq([200, { 7 => 2 }])
    expect(held_row_company_writes).to eq([200, { 7 => 2 }])
  end
end

