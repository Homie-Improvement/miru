# frozen_string_literal: true

require "rails_helper"

# GET /internal/v1/metrics answers every company's write counts, so only the
# service token may read it.
RSpec.describe "Timekeeping internal write metrics" do
  let(:metrics_service_token) { "service-#{SecureRandom.hex(24)}" }
  let(:unauthorized_body) { { "reason" => "unauthorized" } }

  around do |example|
    with_timekeeping_env(
      Timekeeping::Environment::TOKEN_PUBLIC_KEY => rsa_key_pair.public_key.to_pem,
      Timekeeping::Environment::SERVICE_TOKEN => metrics_service_token
    ) { example.run }
  end

  def get_metrics(authorization)
    headers = authorization ? { "Authorization" => authorization } : {}
    get "/internal/v1/metrics", headers: headers
    [response.status, response.parsed_body]
  end

  def record_metric_for_spec(company_id, at, outcome: :write, latency_ms: 40)
    Timekeeping::WriteMetrics.new(clock: -> { at }).record(company_id:, outcome:, latency_ms:)
  end

  describe "refusals" do
    it "refuses every bearer when TIMEKEEPING_SERVICE_TOKEN is empty" do
      with_timekeeping_env(Timekeeping::Environment::SERVICE_TOKEN => "") do
        expect(get_metrics("Bearer ")).to eq([401, unauthorized_body])
        expect(get_metrics("Bearer #{metrics_service_token}")).to eq([401, unauthorized_body])
        expect(get_metrics("Bearer anything")).to eq([401, unauthorized_body])
      end
    end

    it "refuses an owner user token" do
      token = mint_token({ sub: 7, company_id: 1, role: "owner" })

      expect(get_metrics("Bearer #{token}")).to eq([401, unauthorized_body])
    end

    it "refuses an admin user token" do
      token = mint_token({ sub: 7, company_id: 1, role: "admin" })

      expect(get_metrics("Bearer #{token}")).to eq([401, unauthorized_body])
    end

    it "refuses a wrong service token" do
      expect(get_metrics("Bearer #{metrics_service_token}x")).to eq([401, unauthorized_body])
    end

    it "refuses a signed service token, which is bound to one company" do
      now = Time.now.to_i
      token = JWT.encode({ typ: "timekeeping_service", sub: "invoice-boundary", company_id: 1,
                           operations: Timekeeping::ReservationAccess::ROUTE_OPERATIONS.values, iat: now,
                           exp: now + 60, jti: SecureRandom.uuid }, rsa_key_pair, "RS256")

      expect(get_metrics("Bearer #{token}")).to eq([401, unauthorized_body])
    end

    it "refuses a request with no Authorization header" do
      expect(get_metrics(nil)).to eq([401, unauthorized_body])
    end
  end

  describe "with the service token" do
    it "answers each window under its own company, with the bucket bounds and no cross-company totals" do
      window = Time.utc(2026, 3, 3, 12)
      record_metric_for_spec(2, window + 10)
      record_metric_for_spec(1, window + 20, latency_ms: 350)
      record_metric_for_spec(1, window + 30, outcome: :reference_unavailable)
      record_metric_for_spec(1, window + 300)

      status, body = get_metrics("Bearer #{metrics_service_token}")

      expect(status).to eq(200)
      expect(body).to eq(
        "window_seconds" => 300,
        "latency_bucket_bounds_ms" => [25, 50, 100, 200, 300, 500, 1000, 2500, 5000],
        "overflow_bucket" => "inf",
        "total_field" => "writes + reference_unavailable",
        "companies" => [
          {
            "company_id" => 1,
            "windows" => [
              { "window_start" => "2026-03-03T12:00:00Z", "writes" => 1, "reference_unavailable" => 1,
                "latency_ms_sum" => 390, "latency_ms_buckets" => { "50" => 1, "500" => 1 } },
              { "window_start" => "2026-03-03T12:05:00Z", "writes" => 1, "reference_unavailable" => 0,
                "latency_ms_sum" => 40, "latency_ms_buckets" => { "50" => 1 } }
            ]
          },
          {
            "company_id" => 2,
            "windows" => [
              { "window_start" => "2026-03-03T12:00:00Z", "writes" => 1, "reference_unavailable" => 0,
                "latency_ms_sum" => 40, "latency_ms_buckets" => { "50" => 1 } }
            ]
          }
        ],
        "outbox_lag" => []
      )
    end

    it "answers an empty companies list when nothing has been recorded" do
      status, body = get_metrics("Bearer #{metrics_service_token}")

      expect([status, body.fetch("companies")]).to eq([200, []])
    end
  end

  # Generated by Descant: acceptance tests below.
  describe "while a company's window row is held" do
    include_context "timekeeping entry writes without transactional fixtures"

    # [status, each company's total writes] as the endpoint answers them.
    def held_row_metric_writes
      status, body = get_metrics("Bearer #{metrics_service_token}")
      [status, body.fetch("companies").to_h do |company|
        [company["company_id"], company["windows"].sum { |window| window["writes"] }]
      end]
    end

    # "treat response delivery independently from metric persistence as follow-up
    # work that preserves counts rather than discarding timed-out events."
    it "answers metrics while one company's window row is held, keeps that company's pending write, and counts it once on the next read" do
      stub_const("Timekeeping::WriteMetrics::LOCK_TIMEOUT_MS", 1000)
      at = Time.utc(2026, 3, 3, 12, 0, 10)
      record_metric_for_spec(1, at)
      Timekeeping::WriteMetrics.fold_pending
      record_metric_for_spec(1, at)
      record_metric_for_spec(2, at)

      holder, release, holding_pid = hold_metric_window_row(1)
      # The read runs on this thread, so the wait is watched from another one.
      watcher = Thread.new do
        ApplicationRecord.connection_pool.with_connection { metric_lock_waiter_seen?(holding_pid) }
      end

      answer_while_held = held_row_metric_writes
      blocked = watcher.join(10)&.value
      release << true
      holder.join(10)

      expect(blocked).to be(true), "the metrics read never waited on the held window row"
      expect(answer_while_held).to eq([200, { 1 => 1, 2 => 1 }])
      expect(held_row_metric_writes).to eq([200, { 1 => 2, 2 => 1 }])
      expect(held_row_metric_writes).to eq([200, { 1 => 2, 2 => 1 }])
      expect(WriteMetricEvent.count).to eq(0)
    end
  end
end

# Generated by Descant: acceptance tests below.

RSpec.describe "Timekeeping internal metrics for the alert task" do
  include ActiveSupport::Testing::TimeHelpers

  it "answers window_seconds and per-company windows to the service token but refuses a company owner's own token" do
    service_token = "service-#{SecureRandom.hex(24)}"
    window = Time.utc(2026, 3, 3, 12)
    Timekeeping::WriteMetrics.new(clock: -> { window + 10 }).record(company_id: 1, outcome: :write, latency_ms: 40)
    Timekeeping::WriteMetrics.new(clock: -> { window + 20 })
                             .record(company_id: 2, outcome: :reference_unavailable, latency_ms: 40)

    with_timekeeping_env(
      Timekeeping::Environment::TOKEN_PUBLIC_KEY => rsa_key_pair.public_key.to_pem,
      Timekeeping::Environment::SERVICE_TOKEN => service_token
    ) do
      owner_token = mint_token({ sub: 7, company_id: 1, role: "owner" })
      get "/internal/v1/metrics", headers: { "Authorization" => "Bearer #{owner_token}" }
      expect([response.status, response.parsed_body]).to eq([401, { "reason" => "unauthorized" }])

      # "Timekeeping's write latency, write counts and `503 reference_unavailable`
      # counts from its `GET /internal/v1/metrics` endpoint, read with the service identity."
      get "/internal/v1/metrics", headers: { "Authorization" => "Bearer #{service_token}" }
    end

    expect(response.status).to eq(200)
    body = response.parsed_body
    expect(body.fetch("window_seconds")).to eq(300)
    counts = body.fetch("companies").to_h do |company|
      window_row = company.fetch("windows").sole
      [company.fetch("company_id"), [window_row.fetch("writes"), window_row.fetch("reference_unavailable")]]
    end
    expect(counts).to eq(1 => [1, 0], 2 => [0, 1])
    expect(response.body).not_to include(service_token)
  end

  # Expose outbox lag (age of the oldest unsent row) with `company_id` on the Timekeeping metrics endpoint.
  it "reports each company's own outbox lag only to the service token" do
    service_token = "service-#{SecureRandom.hex(24)}"
    now = Time.utc(2026, 3, 3, 12)
    # Each entry was created a year ago; only the outbox row's own wait counts.
    lag_row = lambda do |company_id, entry_id, enqueued_at, sent_at = nil|
      outbox_row(id: entry_id, company_id:, enqueued_at:, sent_at:, created_at: now - 1.year, updated_at: now - 1.year)
    end

    with_timekeeping_env(
      Timekeeping::Environment::TOKEN_PUBLIC_KEY => rsa_key_pair.public_key.to_pem,
      Timekeeping::Environment::SERVICE_TOKEN => service_token
    ) do
      travel_to(now) do
        insert_outbox_rows(
          lag_row.call(1, 11, now - 120),
          lag_row.call(1, 12, now - 30),
          lag_row.call(2, 21, now - 10),
          # Company 3's only row is older than every other row but already sent:
          # it must not appear, and its age must not be reported under another company.
          lag_row.call(3, 31, now - 500, now - 400)
        )

        get "/internal/v1/metrics"
        expect(response.status).to eq(401)
        expect(response.parsed_body).to eq("reason" => "unauthorized")

        get "/internal/v1/metrics", headers: { "Authorization" => "Bearer #{service_token}" }
        expect(response.status).to eq(200)
        expect(response.parsed_body.fetch("outbox_lag")).to eq([
          { "company_id" => 1, "oldest_unsent_age_seconds" => 120 },
          { "company_id" => 2, "oldest_unsent_age_seconds" => 10 }
        ])
      end
    end
  end

  it "reports an empty outbox_lag list when no outbox row is unsent" do
    lag_service_token = "service-#{SecureRandom.hex(24)}"
    with_timekeeping_env(
      Timekeeping::Environment::TOKEN_PUBLIC_KEY => rsa_key_pair.public_key.to_pem,
      Timekeeping::Environment::SERVICE_TOKEN => lag_service_token
    ) do
      get "/internal/v1/metrics", headers: { "Authorization" => "Bearer #{lag_service_token}" }
    end

    expect([response.status, response.parsed_body.fetch("outbox_lag")]).to eq([200, []])
  end
end
